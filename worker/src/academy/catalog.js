export function findCourse(id) {
  return COURSES.find((c) => c.id === id) || null;
}

export function findLesson(course, lessonId) {
  return course.lessons.find((l) => l.id === lessonId) || null;
}

/** نمای فهرست: بدون متن درس‌ها */
export function courseSummaries() {
  return COURSES.map((c) => ({
    id: c.id,
    title: c.title,
    level: c.level,
    summary: c.summary,
    lessonCount: c.lessons.length,
    status: c.status,
  }));
}

/** دوره‌ای که هنوز پیش‌نویس است، برای کاربر عادی ثبت‌نام و محتوا ندارد. */
export function isPublicCourse(course) {
  return Boolean(course) && course.status === 'published';
}
