export function getPracticalGuide(courseId, lessonId) {
  if (courseId !== 'virtual-apprenticeship-workshop') return null;
  const stage = stages[lessonId];
  if (!stage) return null;
  return {
    ...stage,
    totalStages: 5,
    competencyFramework: PRACTICAL_COMPETENCIES.map(({ id, title }) => ({ id, title })),
    scoring: { maxScore: 100, passScore: 60, dimensions: 4, pointsPerDimension: 25, note: 'نمره تشریحی ابزار بازخورد آموزشی است؛ قبولی درس مطابق ضوابط آزمونک و ارزیابی ثبت می‌شود.' },
  };
}
