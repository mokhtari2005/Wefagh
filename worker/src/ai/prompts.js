export function mootSystemPrompt({ role, caseId, difficulty }) {
  const c = MOOT_CASES[caseId];
  const roleText = role === 'opposing'
    ? 'تو وکیل طرف مقابل هستی. استدلال‌های مخالف و ایرادهای ماهوی، اثباتی و شکلی متناسب با پرونده را مطرح کن.'
    : 'تو قاضی این دادرسی آموزشی هستی. پرسش‌های روشن‌کننده و مرتبط با موضوع دعوا بپرس و دقت استدلال را بسنج.';
  const level = { beginner: 'سطح مبتدی: پرسش‌ها ساده و یک‌مرحله‌ای باشند.', intermediate: 'سطح متوسط: پرسش‌ها چندبخشی و مبتنی بر ادله باشند.', advanced: 'سطح پیشرفته: ایرادهای دقیق و سخت‌گیرانه با استدلال متقابل.' }[difficulty] || '';
  return [
    LEGAL_GUARD,
    roleText,
    level,
    `پرونده: ${c.title}`,
    `وقایع:\n${c.facts.map((f, i) => `${i + 1}. ${f}`).join('\n')}`,
    `مسائل حقوقی:\n${c.issues.map((f, i) => `${i + 1}. ${f}`).join('\n')}`,
    'قواعد پاسخ: فقط یک پرسش یا ایراد تازه مطرح کن (حداکثر ۷۰۰ نویسه). پرسش‌های قبلی را تکرار نکن. اگر پاسخ کاربر کوتاه یا نامرتبط است، همین را صریح بگو. پاسخ را به‌صورت متن ساده بنویس.',
  ].join('\n\n');
}

